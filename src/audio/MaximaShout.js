/**
 * MaximaShout.js — «Максима!», выкрикнутая в столкновении лучей, считается выкриком, даже если распознавание слышит её как сплошной
 * поток («максимум максимум максиму сим максима…»). Автор: «пусть мои выкрики срабатывали, даже если они кажутся непрерывными».
 * Чистый модуль: только текст. Игра подставляет результат, когда герой в столкновении лучей (main.js → voice.onResult).
 */

/** Кусочек слова, похожий на «максима» (как его слышит распознавание): максима, максимум, максиму, мксим, макси, ксим, аксиму, маким, сим… */
const PIECE = /(?:макс|мкс|аксим|ксим|маким|мксим|симум|симу|сима|сим)/;

/** Слово похоже на часть выкрика «Максима»? (короткое «си» тоже — в потоке оно остаётся от «макси-ма»). */
export const maximaLike = (w) => w === 'си' || w === 'ма' || PIECE.test(w);

/**
 * Если фраза — почти сплошь «максима» (не меньше двух слов, не меньше 70% из них похожи) — это один выкрик: 'максима'.
 * Иначе — тот же текст.
 */
export function collapseMaxima(text) {
    const words = String(text || '').toLowerCase().replace(/ё/g, 'е').replace(/[^а-яa-z ]/g, ' ').split(/\s+/).filter(Boolean);
    if (words.length < 2) return text;
    const like = words.filter(maximaLike).length;
    return like >= 2 && like / words.length >= 0.7 ? 'максима' : text;
}
