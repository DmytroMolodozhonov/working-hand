/**
 * PentagramMonster.js — «Пентаграмма страшного монстра»: строка общей таблицы пентаграмм (Pentagrams.js `PENTAGRAMS.monster`)
 * — её рисунок и что делает стоящему на ней (pure, no imports). Рисуют её, как все пентаграммы, «Пентаграниумом» (Pentagranium.js:
 * луч палочки по земле, распознавание PentagramRules.recognize); учится сожжением её свитка-рисунка; превращение —
 * MonsterTransform.js, правила — MonsterForm.js.
 *
 * Рисунок (отличим от звезды дьявольской силы, телепортации, жизни, брони, горгулий, слома защиты, зачарования): КРУГ, а в нём —
 * ОСКАЛЕННАЯ ПАСТЬ одной замкнутой чертой: верхний край — четыре клыка зубцами вниз, от последнего клыка — нижняя челюсть
 * дугой обратно к первому. Ни одной прямой из вершин (как у звёзд), ни квадрата, ни ростка.
 *
 * Чёрная (`dark: true`): +1 к уровню тьмы за каждое превращение (MonsterTransform.begin → addDark(hero, 1, 'ritual')); вид —
 * багрово-чёрный. Одноразовая: встал в горящий круг на 0,8 с — 200 маны — превращение, рисунок выгорает. Маны не хватило —
 * подсказка, рисунок горит дальше (выйти из круга и войти — ещё попытка).
 */

/** Пасть в долях радиуса ([x, z] — как в `draw` других строк таблицы): клыки вниз, челюсть дугой. */
export const MONSTER_JAW = [
    [-0.82, 0.18], [-0.62, -0.22], [-0.41, 0.18], [-0.2, -0.24], [0, 0.18], [0.2, -0.24], [0.41, 0.18], [0.62, -0.22], [0.82, 0.18],
    [0.66, -0.36], [0.36, -0.56], [0, -0.63], [-0.36, -0.56], [-0.66, -0.36],
];

export const MONSTER_STAND = 0.8; // с в круге — и превращение

export const MONSTER_PENTAGRAM = {
    id: 'monster',
    title: 'Пентаграмма страшного монстра',
    dark: true,
    glow: 0xb3121e, // багровое
    cost: 200,      // маны, когда встаёшь в круг (MonsterForm.MONSTER.COST)
    once: true,     // одноразовая: после превращения выгорает
    scroll: 'PentagramMonster',
    draw: [{ t: 'circle', r: 1 }, { t: 'poly', pts: MONSTER_JAW }],
    effect: 'Встаньте в горящий круг — 200 маны — и на 10 минут вы огромный монстр-волкодав, в 7 раз больше человека: без палочки, с кулаками, что ломают дома.',
    /**
     * (Pentagranium._markStep, каждый кадр, пока горит моя пентаграмма) Я стою в круге — через 0,8 с превращение. true — рисунок выгорел.
     * `inside` — ноги в круге, на земле.
     */
    stand(g, m, dt, inside) {
        if (!inside || g.monster?.active) { m._monT = 0; return false; }
        if (m._monT < 0) return false; // (уже пробовали, не вышло: выйти из круга и войти снова)
        m._monT = (m._monT || 0) + dt;
        if (m._monT < MONSTER_STAND) return false;
        m._monT = -1;
        const why = g.monster?.whyNot?.();
        if (why) { g.hud?.setVoice?.(`🐺 ${why}`, true); return false; }
        return !!g.monster?.begin?.();
    },
};
