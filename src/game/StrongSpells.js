/** Accentric: how strong it still is after t s (1 — full, fading from the 40th second to nothing at the 60th). */
export function accentricK(t) {
    const A = STRONG.Accentric;
    if (!(t >= 0) || t >= A.time) return 0;
    return t < A.fade ? 1 : 1 - (t - A.fade) / (A.time - A.fade);
}

/** A creature lost in Accentric's haze: half its blows / spells / shots do not come off. */
export const confusedMiss = (c, r = Math.random) => !!c && c.accT > 0 && r() < 0.5;

/** Pilbidrio: does it blow the body apart? (it had this much health or less before the beam) */
export const pilbidrioBursts = (hpBefore) => Number.isFinite(hpBefore) && hpBefore <= STRONG.Pilbidrio.dmg;

