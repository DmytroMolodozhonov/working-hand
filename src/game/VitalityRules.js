    GAIN_MAX: 5000, // предел прибавки за один обряд (защита от ошибочных чисел)
    TOTAL_MAX: 1000000, // технический предел «бесконечности»
    STAND_K: 0.85, // герой в круге: не дальше этой доли радиуса
    BODY_K: 0.85, // тело лежит в круге: не дальше этой доли радиуса
