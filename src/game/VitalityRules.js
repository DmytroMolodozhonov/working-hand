/** Хит чёрной магии? Флаги удара по существу: `hell` (Hellfire), `dark` (Авада и т. п.), `via: 'alive'` (ожившее дерево), `kind` (заклинание чёрной магии). */
export function darkHit(opts, isDarkKind) {
    if (!opts) return false;
    return !!(opts.hell || opts.dark || opts.via === 'alive' || (opts.kind && isDarkKind?.(opts.kind)));
}

/** Как умер игрок (`Combat.die(.., how)`): чёрной магией ли — 'avada' (Авада), 'Hellfire'. */
export const DARK_DEATH = new Set(['avada', 'AvadaKedavra', 'Hellfire', 'Alive', 'AliveMaxima', 'Accentric']);

/**
 * Годится ли тело для обряда. `b` — тело из Death ({k, bones, stage, lg, dk, mh, rit}); `multiplayer` — сетевая игра (слова автора не уточняли:
 * по умолчанию подходит любое человекоподобное тело, убитое чёрной магией — и житель, и игрок).
 * → {ok, why?}: why — подсказка игроку («это тело не годится: …»).
 */
export function bodyOk(b, { multiplayer = false } = {}) {
    void multiplayer;
    if (!b) return { ok: false, why: 'Нужно тело убитого человекоподобного' };
    if (b.rit || b.vit) return { ok: false, why: 'Это тело уже отдано обряду' };
    if (b.bones || b.stage === 'bones') return { ok: false, why: 'Кости не подходят — нужно тело, которое ещё не стало скелетом' };
    if (b.lg) return { ok: false, why: 'В этом теле лежит сила героя — для обряда оно не подходит' };
    if (b.k !== 'v' && b.k !== 'p') return { ok: false, why: 'Нужно тело человекоподобного: жителя, рыцаря, волшебника, игрока' };
    if (!b.dk) return { ok: false, why: 'Это тело не годится: его убили не чёрной магией (нужна «Авада Кедавра», «Hellfire» и подобные)' };
    return { ok: true };
}

/** Сколько ХП прибавляет жертва: её МАКСИМАЛЬНОЕ здоровье (не текущее), целое, ≥ 1. */
export function gainOf(b) {
    const n = Math.round(Number(b?.mh) || VITAL.BASE_HP);
    return Math.max(1, Math.min(VITAL.GAIN_MAX, n));
}

/** Новый максимум после обряда (с техническим пределом). */
export const grownMax = (max, gain) => Math.min(VITAL.TOTAL_MAX, Math.max(1, Math.round(max || VITAL.BASE_HP)) + gain);

/** Сколько игроков стоит в круге: больше одного — обряд не начинается (одно тело — один герой). */
export const standersOk = (n) => n === 1;

