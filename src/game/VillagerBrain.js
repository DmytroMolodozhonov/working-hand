function plural(n, one, few, many) {
    const a = Math.abs(n) % 100, b = a % 10;
    if (a > 10 && a < 20) return many;
    if (b === 1) return one;
    if (b >= 2 && b <= 4) return few;
    return many;
}
export function coinsNom(n) { return `${n} ${plural(n, 'монета', 'монеты', 'монет')}`; }
export function coinsAcc(n) { return `${n} ${plural(n, 'монету', 'монеты', 'монет')}`; }

/** Accusative of an inanimate goods phrase («свежая рыба» → «свежую рыбу»). */
function accusative(phrase) {
    return String(phrase).split(' ').map((w) => {
        if (/ая$/.test(w)) return w.replace(/ая$/, 'ую');
        if (/яя$/.test(w)) return w.replace(/яя$/, 'юю');
        if (/[^и]а$/.test(w)) return w.replace(/а$/, 'у');
        if (/я$/.test(w) && !/(ие|ье)$/.test(w)) return w.replace(/я$/, 'ю');
        return w;
    }).join(' ');
}

function itemName(item) {
    if (!item) return 'товар';
    if (typeof item === 'string') return item.toLowerCase();
    return String(item.name || 'товар').toLowerCase();
}

