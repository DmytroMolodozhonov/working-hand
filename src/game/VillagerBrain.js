/** True when most letters of `s` are Cyrillic. */
export function isMostlyRussian(s) {
    const letters = String(s).match(/[a-zа-яё]/gi) || [];
    if (letters.length < 2) return false;
    const cyr = letters.filter((c) => /[а-яё]/i.test(c)).length;
    return cyr / letters.length >= 0.85;
}

/** Cleans an LLM answer: drops <think>, quotes, speaker labels, keeps ≤ 2 sentences. */
export function sanitizeReply(text, speakerName = '') {
    let s = String(text ?? '');
    s = s.replace(/<think>[\s\S]*?<\/think>/gi, ' ');
    s = s.replace(/<think>[\s\S]*$/i, ' '); // unclosed think block
    s = s.replace(/<\/?[a-z_|]+[^>]*>/gi, ' '); // leftover special tokens
    s = s.replace(/[*_#`~]+/g, ' ');
    s = s.replace(/[\u{1F000}-\u{1FFFF}\u{2600}-\u{27BF}]/gu, ' ');
    s = s.replace(/\s+/g, ' ').trim();
    if (speakerName) s = s.replace(new RegExp(`^${speakerName}\\s*[:\\-—]\\s*`, 'i'), '');
    s = s.replace(/^(ответ|реплика|персонаж|villager|assistant|ассистент)\s*[:\-—]\s*/i, '');
    s = s.replace(/^[«"'„“]+|[»"'“”]+$/g, '').trim();
    const sentences = s.match(/[^.!?…]+[.!?…]*/g) || [];
    s = sentences.slice(0, 2).join(' ').replace(/\s+/g, ' ').trim();
    if (s.length > 220) s = s.slice(0, 220).replace(/\s+\S*$/, '') + '…';
    return s;
}

