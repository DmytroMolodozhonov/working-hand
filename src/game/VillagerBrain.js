function parseNumber(t) {
    const d = t.match(/\d+/);
    if (d) return parseInt(d[0], 10);
    let sum = 0, found = false;
    for (const tok of t.split(' ')) {
        if (NUMBER_WORDS[tok] !== undefined) { sum += NUMBER_WORDS[tok]; found = true; }
        else if (found) break;
    }
    return found ? sum : null;
}

