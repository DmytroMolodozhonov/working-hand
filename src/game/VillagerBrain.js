/**
 * Detects what the player means.
 * @param {string} text raw transcript
 * @returns {{ intent: string, slots: object, all: string[], text: string }}
 */
export function detectIntent(text) {
    const t = normalize(text);
    const slots = {};
    const all = [];
    if (!t) return { intent: 'unknown', slots, all, text: t };
    const tokens = t.split(' ');

    // slots that any intent may use
    for (const g of GOODS) if (g.re.test(t)) { slots.item = g.name; break; }
    if (MAGIC_WORDS.test(t)) slots.magic = true;
    const n = parseNumber(t);
    if (n !== null) slots.number = n;

    for (const [intent, re] of RULES) {
        if (intent === 'yes') {
            if (tokens.length <= 5 && !all.includes('no') && (YES_FIRST.has(tokens[0]) || YES_PHRASE.test(t) || (tokens[0] === 'ну' && YES_FIRST.has(tokens[1])))) all.push('yes');
            continue;
        }
        if (intent === 'no') {
            if (tokens.length <= 5 && NO_RE.test(t)) all.push('no');
            continue;
        }
        if (intent === 'where') {
            if (!WHERE_Q.test(t)) continue;
            if (T_MARKET.test(t)) all.push('where_market');
            else if (T_THRONE.test(t)) all.push('where_throne');
            else if (T_KING.test(t)) all.push('where_king');
            else if (T_GATE.test(t)) all.push('where_gate');
            else {
                const p = PLACES.find((pl) => pl.re.test(t));
                if (p) { all.push('where_other'); slots.place = p.place; }
            }
            continue;
        }
        if (re.test(t) && !all.includes(intent)) all.push(intent);
    }

    if (all.includes('tell_name')) {
        const m = t.match(/(?:меня зовут|мое имя|зови меня|называй меня|я зовусь|имя мое|меня звать|меня кличут)\s+([а-яa-z]+)/);
        if (m && !NAME_STOP.has(m[1]) && m[1].length >= 2) slots.name = capitalize(m[1]);
    }

    // "я не дурак" / "ты не дурак" is not an insult; "не убью" is not a threat
    if (all.includes('insult') && /(?<![а-я])(не|я не) (дурак|дура|тупой|тупая|идиот|глупый|глупая)/.test(t) && !/ты (дурак|дура|тупой|идиот)/.test(t)) {
        all.splice(all.indexOf('insult'), 1);
    }
    if (all.includes('threat') && /(?<![а-я])не (убью|трону|обижу|ударю|побью)/.test(t)) all.splice(all.indexOf('threat'), 1);
    // «я убью всех зомби» is zombie talk, not a threat to the villager
    if (all.includes('threat') && /(?<![а-я])(зомби|мертвец|мертвяк|нежит|монстр|чудовищ|скелет)/.test(t) && !/(?<![а-я])(тебя|вас)(?![а-я])/.test(t)) all.splice(all.indexOf('threat'), 1);
    let intent = all[0] || 'unknown';
    // «да, а где рынок?» / «давай за пять» — the content intent wins over a leading yes/no
    if (intent === 'yes' || intent === 'no') {
        const content = all.find((i) => ['price', 'browse', 'sell', 'bye'].includes(i) || i.startsWith('where_') || (i === 'haggle' && slots.number != null));
        if (content && tokens.length > 2) intent = content;
    }
    // «здравствуйте ваше величество» is a greeting, not a question about the king
    if (all.includes('greet') && tokens.length <= 4 && ['about_king', 'about_castle', 'zombies', 'magic', 'money', 'family', 'weather'].includes(intent)) intent = 'greet';
    if (intent !== all[0] && all.includes(intent)) { all.splice(all.indexOf(intent), 1); all.unshift(intent); }
    return { intent, slots, all, text: t };
}

