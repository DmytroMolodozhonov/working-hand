/** Реплика ситуации `sit` без повтора последних: → индекс или -1. `rnd` — 0…1, `last` — недавние индексы этой ситуации. */
export function pickLine(sit, rnd, last = []) {
    const L = LINES[sit];
    if (!L || !L.length) return -1;
    const free = [];
    for (let i = 0; i < L.length; i++) if (!last.includes(i)) free.push(i);
    const pool = free.length ? free : L.map((_, i) => i);
    return pool[Math.floor(rnd * pool.length) % pool.length];
}
