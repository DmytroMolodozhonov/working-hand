const clamp01 = (v) => Math.max(0, Math.min(1, v));

/** Можно ли взять: {ok, why}. `kind` — ключ GRAB_TARGETS. */
export function grabVerdict(kind) {
    const r = GRAB_TARGETS[kind];
    if (!r) return { ok: false, why: 'лапа это не берёт' };
    return { ok: r.does === 'grab', why: r.why };
}

/** Помещается ли тело длиной `len` м в кулак монстра ростом `size`. */
export const fits = (len, size = GRAB_RULES.SCALE) => len <= GRAB_RULES.FIT_MAX * (size / GRAB_RULES.SCALE);

/** Кулак «до конца» этого игрока (выученный у его кисти — ThrowModel.HandTrack.closedRef). */
export const fistOf = (closedRef) => Math.max(GRAB_RULES.FIST_MIN, Math.min(GRAB_RULES.FIST_MAX, (closedRef || 0.9) - 0.02));

/** Сжатие 0…1 из пальцев игрока: до SQ_FROM — просто держит; до своего кулака — сильнее. */
export function squeezeOf(curl, closedRef) {
    const R = GRAB_RULES, top = fistOf(closedRef);
    return clamp01((curl - R.SQ_FROM) / Math.max(0.05, top - R.SQ_FROM));
}

/** Сглаживание сжатия за кадр (дрожь пальцев не давит, настоящее сжатие доходит за ~0,15 с). */
export const smoothSqueeze = (prev, k, dt) => prev + (k - prev) * (1 - Math.exp(-dt / GRAB_RULES.SQ_TAU));

/** ХП в секунду от сжатия `k` (0 — держит, без урона). */
export function squeezeDps(k) {
    const R = GRAB_RULES;
    if (k <= R.DMG_FROM) return 0;
    const u = (k - R.DMG_FROM) / (1 - R.DMG_FROM);
    return R.DPS * u * u;
}

/**
 * Шаг давления: `st` — {acc (накоплено ХП), crushT (сек подряд «до конца»), tick}. → {dmg (целое — списать сейчас), crush (раздавлен)}.
 */
export function squeezeStep(st, k, dt) {
    const R = GRAB_RULES;
    st.acc = (st.acc || 0) + squeezeDps(k) * dt;
    st.crushT = k >= R.CRUSH_K ? (st.crushT || 0) + dt : 0;
    st.tick = (st.tick || 0) + dt;
    if (st.crushT >= R.CRUSH_T) return { dmg: 0, crush: true };
    let dmg = 0;
    if (st.tick >= R.TICK) { st.tick = 0; dmg = Math.floor(st.acc); st.acc -= dmg; }
    return { dmg, crush: false };
}

/** Доля скорости кисти, что получает тело `kg` (лапа и тело качаются вместе) × взмах в конце. */
export const throwGain = (kg) => GRAB_RULES.GAIN * Math.sqrt(GRAB_RULES.ARM_KG / (GRAB_RULES.ARM_KG + Math.max(1, kg)));

/** Скорость вылета тела (м/с) от скорости кисти `handV` (м/с, в мире): × throwGain, не больше V_MAX. */
export const throwSpeed = (handV, kg) => Math.min(GRAB_RULES.V_MAX, Math.max(0, handV) * throwGain(kg));

/** Сжатие так сильно, что держимый волшебник не может колдовать. */
export const choked = (k) => k >= GRAB_RULES.CHOKE;

/** Сколько секунд до того, как волшебник ранга `rank` вырвется заклинанием (null — не вырвется). `rnd` 0…1. */
export function wizardFreeT(rank, rnd = Math.random()) {
    const r = WIZ_FREE[rank === 'head' ? 'master' : rank];
    if (!r) return null;
    return r[0] + (r[1] - r[0]) * rnd;
}

/** Что показывают пальцы лапы: ложатся на тело (`wrap` — обхват по телу), сжатие вдавливает их глубже, разжатые — как есть. */
export function shownCurl(real, wrap, k) {
    if (real <= wrap) return real;
    return Math.min(real, wrap + (1 - wrap) * 0.55 * k);
}

